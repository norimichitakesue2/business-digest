# validate sent/kind domains
NSENT={"pos","neg","mix","drv"}; EKIND={"pos","neg","mix","ease"}
errs=[]
def chk_flow(fl,tag):
    for nid,v in fl["nodes"].items():
        if v[2] not in NSENT: errs.append(f"{tag} node {nid} sent={v[2]}")
    for e in fl["edges"]:
        if e[2] not in EKIND: errs.append(f"{tag} edge {e[0]}->{e[1]} kind={e[2]}")
